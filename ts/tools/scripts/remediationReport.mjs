import { randomUUID } from "node:crypto";
import {
    appendFileSync,
    existsSync,
    readFileSync,
    writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const counters = [
    "resolved",
    "blocked",
    "no_patch",
    "deferred",
    "min_release_age_days",
    "failed",
    "skipped",
];
const lists = [
    "applied_packages",
    "rolled_back_packages",
    "skipped_packages",
    "blocked_packages",
    "no_patch_packages",
    "deferred_packages",
    "failed_workspaces",
];
const outputFields = [...counters, ...lists];

function validateOutputs(input) {
    if (!input || typeof input !== "object" || Array.isArray(input)) {
        throw new Error("Remediation outputs must be an object.");
    }
    const result = {};
    for (const key of outputFields) {
        const value = input[key] ?? "";
        if (typeof value !== "string") {
            throw new Error(`Remediation output ${key} must be a string.`);
        }
        if (
            counters.includes(key) &&
            value !== "" &&
            (!/^\d+$/.test(value) || !Number.isSafeInteger(Number(value)))
        ) {
            throw new Error(`Remediation output ${key} must be an integer.`);
        }
        result[key] = value;
    }
    const changes = input.changes ?? "";
    if (!["", "true", "false"].includes(changes)) {
        throw new Error("Remediation changes output must be true or false.");
    }
    result.changes = changes;
    return result;
}

function codeBlock(text) {
    const longest = Math.max(
        2,
        ...(text.match(/`+/g) ?? []).map((match) => match.length),
    );
    const fence = "`".repeat(longest + 1);
    return `${fence}\n${text}\n${fence}`;
}

export function renderRemediationReport(input, options = {}) {
    const data = validateOutputs(input);
    const count = (key) => data[key] || "0";
    const shell = options.shellOk ? "passed" : "skipped";
    const commit = `fix: remediate Dependabot security alerts

Automated by fix-dependabot-alerts workflow.

Applied:${data.applied_packages}
Rolled back:${data.rolled_back_packages || " (none)"}
Blocked: ${count("blocked")} package(s)
Deferred (min release age): ${count("deferred")} package(s)
Shell packaging: ${shell}

Co-authored-by: github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>
`;
    const body = [
        "## Automated Dependabot Alert Remediation",
        "",
        "This PR was automatically generated by the `fix-dependabot-alerts` workflow.",
        "Each fix was applied individually and build-verified before inclusion.",
        "",
        "### Summary",
        `- **Applied (${count("resolved")}):**${data.applied_packages}`,
        `- **Blocked (${count("blocked")}):**${data.blocked_packages || " (none)"}`,
        `- **No patch available (${count("no_patch")}):**${data.no_patch_packages || " (none)"}`,
        `- **Deferred (${count("deferred")}):**${data.deferred_packages || " (none)"}`,
        `- **Rolled back (${count("failed")}):**${data.rolled_back_packages || " (none)"}`,
        `- **Skipped (recent rollback, ${count("skipped")}):**${data.skipped_packages || " (none)"}`,
        `- **Workspaces with analysis failures:**${data.failed_workspaces || " (none)"}`,
        "- **Build:** Passed",
        `- **Shell packaging:** ${shell}`,
        "",
        "> The analysis also audits the lockfile directly. Its results can differ from the GitHub Dependabot REST API.",
    ];
    if (Number(count("deferred")) > 0) {
        body.push(
            "",
            `> Deferred fixes require a version published for at least ${data.min_release_age_days || "7"} days. They will be reconsidered once a qualifying version matures.`,
        );
    }
    if (options.chains) {
        body.push(
            "",
            "### Why blocked packages could not be auto-fixed",
            "<details><summary>Dependency chains</summary>",
            "",
            codeBlock(options.chains),
            "",
            "</details>",
        );
    }
    body.push(
        "",
        "### How this works",
        "1. Analyses open Dependabot alerts and the lockfile",
        "2. Applies each fix individually with build verification",
        "3. Rolls back fixes that break the build",
        "4. Includes only verified fixes",
        "",
        "### Review checklist",
        "- [ ] Check for breaking changes",
        "- [ ] Investigate rolled-back packages",
        "- [ ] Run relevant tests",
    );
    const summary = [
        "## Dependabot Alert Remediation",
        "",
        "| Metric | Count |",
        "|--------|-------|",
        `| Applied | ${count("resolved")} |`,
        `| Blocked | ${count("blocked")} |`,
        `| No patch available | ${count("no_patch")} |`,
        `| Deferred (min release age) | ${count("deferred")} |`,
        `| Rolled back | ${count("failed")} |`,
        "",
    ];
    for (const [key, label] of [
        ["applied_packages", "Applied"],
        ["rolled_back_packages", "Rolled back"],
        ["deferred_packages", "Deferred (waiting for minimum release age)"],
        ["failed_workspaces", "Analysis failed for workspaces"],
    ]) {
        if (data[key]) summary.push(`**${label}:**${data[key]}`);
    }
    if (options.fixOutcome !== undefined && options.fixOutcome !== "success") {
        summary.push("", "Analysis did not complete successfully.");
    } else if (data.changes === "true") {
        summary.push(
            "",
            options.prCreated
                ? "Changes applied and PR created."
                : "Changes prepared, but no PR was created.",
        );
    } else {
        summary.push(
            "",
            options.dryRun
                ? "Dry run: no changes applied."
                : "No fixable alerts found.",
        );
    }
    return {
        commitMessage: commit,
        prBody: body.join("\n") + "\n",
        summary: summary.join("\n") + "\n",
    };
}

export function appendRemediationOutputs(path, input) {
    const data = validateOutputs(input);
    const records = outputFields.map((key) => {
        let delimiter;
        do {
            delimiter = `remediation_${randomUUID()}`;
        } while (data[key].includes(delimiter));
        return `${key}<<${delimiter}\n${data[key]}\n${delimiter}\n`;
    });
    appendFileSync(path, records.join(""), "utf8");
}

function run(mode) {
    if (mode === "outputs") {
        const input = Object.fromEntries(
            outputFields.map((key) => [
                key,
                process.env[`FIX_${key.toUpperCase()}`] ?? "",
            ]),
        );
        if (!process.env.GITHUB_OUTPUT) {
            throw new Error("GITHUB_OUTPUT is required.");
        }
        appendRemediationOutputs(process.env.GITHUB_OUTPUT, input);
        return;
    }
    const input = JSON.parse(process.env.REMEDIATION_OUTPUTS ?? "{}");
    const chainPath = process.env.REMEDIATION_CHAIN_FILE;
    const reports = renderRemediationReport(input, {
        shellOk: process.env.REMEDIATION_SHELL_OK === "true",
        dryRun: process.env.REMEDIATION_DRY_RUN === "true",
        prCreated: process.env.REMEDIATION_PR_CREATED === "true",
        fixOutcome: process.env.REMEDIATION_FIX_OUTCOME,
        chains:
            chainPath && existsSync(chainPath)
                ? readFileSync(chainPath, "utf8")
                : "",
    });
    if (mode === "files" && process.env.RUNNER_TEMP) {
        writeFileSync(
            join(process.env.RUNNER_TEMP, "remediation-commit.txt"),
            reports.commitMessage,
            "utf8",
        );
        writeFileSync(
            join(process.env.RUNNER_TEMP, "remediation-pr.md"),
            reports.prBody,
            "utf8",
        );
    } else if (mode === "summary" && process.env.GITHUB_STEP_SUMMARY) {
        appendFileSync(
            process.env.GITHUB_STEP_SUMMARY,
            reports.summary,
            "utf8",
        );
    } else {
        throw new Error("A valid report mode and destination are required.");
    }
}

const script = fileURLToPath(import.meta.url);
const invoked = process.argv[1] && resolve(process.argv[1]);
const isMain =
    invoked &&
    (process.platform === "win32"
        ? invoked.toLowerCase() === script.toLowerCase()
        : invoked === script);
if (isMain) {
    try {
        run(process.argv[2]);
    } catch (error) {
        console.error(`::error::${error.message}`);
        process.exitCode = 1;
    }
}
